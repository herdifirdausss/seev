// Command doccatalog generates docs/catalog.md from the docs/ directory tree.
// It reads YAML frontmatter (status, owner, last_reviewed, canonical_for, generated,
// plan_id) when present and emits a full document inventory table.
// Run: go run ./tools/doccatalog
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type docEntry struct {
	path        string
	title       string
	status      string
	owner       string
	lastReview  string
	canonicalFor string
	planID      string
	generated   string
}

func main() {
	root, err := os.Getwd()
	if err != nil {
		fatalf("getwd: %v", err)
	}

	docsDir := filepath.Join(root, "docs")
	var entries []docEntry

	err = filepath.WalkDir(docsDir, func(path string, d os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			name := d.Name()
			if strings.HasPrefix(name, ".") || name == "node_modules" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.EqualFold(filepath.Ext(path), ".md") {
			return nil
		}
		rel, relErr := filepath.Rel(root, path)
		if relErr != nil {
			return relErr
		}
		e := parseDoc(path, filepath.ToSlash(rel))
		entries = append(entries, e)
		return nil
	})
	if err != nil {
		fatalf("walk: %v", err)
	}

	sort.Slice(entries, func(i, j int) bool {
		return entries[i].path < entries[j].path
	})

	out := filepath.Join(docsDir, "catalog.md")
	f, err := os.Create(out)
	if err != nil {
		fatalf("create catalog: %v", err)
	}
	defer f.Close()

	w := bufio.NewWriter(f)
	fmt.Fprintf(w, "# Document Catalog\n\n")
	fmt.Fprintf(w, "> **Status: Generated.** This file is generated by `make docs-catalog`.\n")
	fmt.Fprintf(w, "> Do not edit by hand. The source of truth is the `docs/` directory tree.\n")
	fmt.Fprintf(w, "> Generated: %s\n\n", "2026-08-09")
	fmt.Fprintf(w, "| Path | Title | Status | Owner | Last reviewed | Canonical for | Plan ID | Generated |\n")
	fmt.Fprintf(w, "|---|---|---|---|---|---|---|---|\n")

	for _, e := range entries {
		// Render as a markdown link in the path column.
		link := fmt.Sprintf("[%s](%s)", e.path, "../"+e.path)
		fmt.Fprintf(w, "| %s | %s | %s | %s | %s | %s | %s | %s |\n",
			link,
			escape(e.title),
			escape(e.status),
			escape(e.owner),
			escape(e.lastReview),
			escape(e.canonicalFor),
			escape(e.planID),
			escape(e.generated),
		)
	}
	w.Flush()

	fmt.Printf("doccatalog: wrote %d entries to %s\n", len(entries), out)
}

func parseDoc(path, relPath string) docEntry {
	e := docEntry{path: relPath}

	f, err := os.Open(path)
	if err != nil {
		return e
	}
	defer f.Close()

	scanner := bufio.NewScanner(f)
	inFrontmatter := false
	frontmatterDone := false
	lineNum := 0

	for scanner.Scan() {
		line := scanner.Text()
		lineNum++

		if lineNum == 1 && line == "---" {
			inFrontmatter = true
			continue
		}
		if inFrontmatter {
			if line == "---" {
				frontmatterDone = true
				inFrontmatter = false
				continue
			}
			key, value, found := strings.Cut(line, ":")
			if !found {
				continue
			}
			key = strings.TrimSpace(key)
			value = strings.TrimSpace(value)
			switch key {
			case "status":
				e.status = value
			case "owner":
				e.owner = value
			case "last_reviewed":
				e.lastReview = value
			case "canonical_for":
				e.canonicalFor = value
			case "plan_id":
				e.planID = strings.Trim(value, `"`)
			case "generated":
				e.generated = value
			}
			continue
		}

		// Extract title from first ATX heading.
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "#") && e.title == "" {
			e.title = strings.TrimSpace(strings.TrimLeft(trimmed, "#"))
		}

		// Stop after frontmatter + title.
		if frontmatterDone && e.title != "" {
			break
		}
		if !inFrontmatter && lineNum > 30 && e.title != "" {
			break
		}
	}

	if e.status == "" {
		// Infer from path.
		switch {
		case strings.Contains(relPath, "roadmap/archive/"):
			e.status = "historical"
		case strings.Contains(relPath, "roadmap/active/"):
			e.status = "active"
		case strings.Contains(relPath, "reviews/archive/"):
			e.status = "historical"
		case strings.Contains(relPath, "evidence/"):
			e.status = "evidence"
		}
	}

	return e
}

func escape(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	if s == "" {
		return "—"
	}
	return s
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "doccatalog: "+format+"\n", args...)
	os.Exit(1)
}
